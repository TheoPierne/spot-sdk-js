/**
 * Reads a streamed response to recreate a ChoreographyStateLog proto.
 * @param {choreographySequencePb.DownloadRobotStateLogResponse[]} response Streamed response with the
 * choreography log.
 * @returns {{
 * initialStatus: choreographySequencePb.DownloadRobotStateLogResponse.Status,
 * choreographyLog: choreographySequencePb.ChoreographyStateLog
 * }}
 */
function _getStreamedChoreographyStateLog(response) {
  let data = [];
  let numChunks = 0;
  let initialStatus = null;
  for (const res of response) {
    if (numChunks === 0) {
      initialStatus = res.getStatus();
    }
    data.push(...res.getChunk().getData());
    numChunks++;
  }

  let choreographyLog;
  if (numChunks > 0) {
    choreographyLog = choreographySequencePb.ChoreographyStateLog.deserializeBinary(data);
  }

  return { initialStatus, choreographyLog };
}

/**
 * Read a choreography sequence file into a protobuf ChoreographySequence message.
 * @param {string} filePath The file containing binary data
 * @returns {choreographySequencePb.ChoreographySequence}
 */
function loadChoreographySequenceFromBinaryFile(filePath) {
  if (!existsSync(filePath)) {
    throw new Error(`File not found at ${filePath}`);
  }

  const data = readFileSync(filePath, 'utf-8');
  return choreographySequencePb.ChoreographySequence.deserializeBinary(data);
}

