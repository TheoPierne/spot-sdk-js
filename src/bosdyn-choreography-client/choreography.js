  buildChoreographyTimeAdjustRequest(overrideClientStartTime, timeDifference, validityTime) {
    const request = new choreographySequencePb.ChoreographyTimeAdjustRequest();
    if (overrideClientStartTime) {
      request.setOverrideStartTime(this._updateTimestampFilter(overrideClientStartTime, this.timesyncEndpoint));
    }
    if (timeDifference) {
      request.setAcceptableTimeDifference(secondsToDuration(timeDifference));
    }
    if (validityTime) {
      request.setValidityTime(secondsToDuration(validityTime));
    }
    return request;
  }

