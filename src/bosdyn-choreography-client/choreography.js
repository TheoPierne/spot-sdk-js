/**
 * Saves a choreography sequence to a file.
 * @param {string} filePath The path to save the file
 * @param {string} fileName The file name
 * @param {choreographySequencePb.ChoreographySequence} choreography The choreography sequence to save
 */
function saveChoreographySequenceToFile(filePath, fileName, choreography) {
  if (!fileName) {
    throw new Error('Invalid file name, cannot save choreography sequence.');
  }

  if (!existsSync(filePath)) {
    console.error(`Path(${filePath}) to save file does not exist. Creating it.`);
    mkdirSync(filePath, { recursive: true });
  }

  const data = choreography.serializeBinary();
  writeFileSync(join(filePath, fileName), data);
}

