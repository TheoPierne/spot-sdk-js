  /**
   * @param {Robot} other 
   */
  async updateFrom(other) {
    super.updateFrom(other);
    if (this.leaseWallet) {
      addLeaseWalletProcessors(this, this.leaseWallet);
    }

    try {
      this._timesyncEndpoint = (await other.timeSync).endpoint;
    } catch (err) {
      // pass
    }
  }

  /**
   * Timesync endpoint for the robot
   * @type {TimeSyncEndpoint}
   * @throws {NoTimeSyncError}
   * @readonly
   */
  get timesyncEndpoint() {
    if (!this._timesyncEndpoint) {
      throw new NoTimeSyncError(null, '[choreography service] No timesync endpoint set for the robot');
    }

    return this._timesyncEndpoint;
  }

